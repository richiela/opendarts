"""The dashboard's tab panels must be well-formed <div> trees.

Why this exists: on 2026-09-13 a commit that regrouped the Config tab's
boxes left one extra `</div>` behind. It closed `#tab-config` early, so
the Server address box fell OUTSIDE every tab panel and rendered on top
of whatever tab was actually selected -- the Engines tab showed a server
setting above its results table.

Nothing caught it. The suite had 2,334 tests, `node --check` parsed the
inline JavaScript, and the markup is generated by an f-string that
Python was perfectly happy to format. An unbalanced div is not a syntax
error in any of those senses; it is only wrong as a tree, and nothing
was checking the tree.
"""
from __future__ import annotations

import re
from types import SimpleNamespace

from opendarts.live.server import _render_dashboard_html

_DIV_TOKEN = re.compile(r"<div\b[^>]*>|</div>")
_PANEL_OPEN = re.compile(r'<div id="(tab-[a-z-]+)" class="tab-panel')


def _panels(html: str) -> dict[str, int]:
    return {m.group(1): m.start() for m in _PANEL_OPEN.finditer(html)}


def test_no_markup_escapes_between_tab_panels():
    """A panel must stay open until the next one begins.

    The weaker check -- "does each panel reach depth 0 somewhere?" -- is
    not enough, and this was confirmed by re-inserting the real bug: an
    extra `</div>` simply closes the panel EARLIER and still balances, so
    a naive walk sees nothing wrong. What actually went wrong is that
    content ended up in the gap between one panel closing and the next
    opening, where it belongs to no tab and therefore shows on all of
    them. That gap is the thing to assert on.
    """
    html = _render_dashboard_html(3)
    starts = sorted(_panels(html).items(), key=lambda kv: kv[1])
    assert starts, "no tab panels found -- the selector has drifted"

    for index, (name, start) in enumerate(starts):
        if index + 1 >= len(starts):
            break
        next_name, next_start = starts[index + 1]

        depth = 0
        closed_at = None
        for token in _DIV_TOKEN.finditer(html, start):
            if token.start() >= next_start:
                break
            depth += -1 if token.group(0).startswith("</") else 1
            if depth == 0:
                closed_at = token.end()
                break
        assert closed_at is not None, f"{name} never closes before {next_name}"

        gap = html[closed_at:next_start]
        gap = re.sub(r"<!--.*?-->", "", gap, flags=re.S).strip()
        assert not gap, (
            f"{len(gap)} chars are stranded between {name} closing and "
            f"{next_name} opening -- content there belongs to no tab and "
            f"renders on every one of them:\n{gap[:300]}"
        )


def test_server_address_control_lives_inside_the_config_tab():
    """The specific regression: a Config control escaping into every tab.

    Pinned by id rather than by prose so it keeps working if the section
    is reworded.
    """
    html = _render_dashboard_html(3)
    start = _panels(html)["tab-config"]

    depth = 0
    end = None
    for token in _DIV_TOKEN.finditer(html, start):
        depth += -1 if token.group(0).startswith("</") else 1
        if depth == 0:
            end = token.end()
            break
    assert end is not None

    body = html[start:end]
    for control in ('id="server-port"', 'id="server-host"'):
        assert control in body, f'{control} is outside #tab-config'


def test_tab_title_leads_with_the_machine_name(monkeypatch):
    """With several rigs open, every tab used to read the same thing.

    Patches the module REFERENCE, not platform.node itself: the latter
    is the shared stdlib module, visible to every thread for the
    duration of the test.
    """
    import opendarts.live.server as server
    monkeypatch.setattr(server, "platform", SimpleNamespace(node=lambda: "macrig.local"))
    html = _render_dashboard_html(3)
    assert "<title>macrig - opendarts dashboard</title>" in html


def test_tab_title_escapes_the_machine_name(monkeypatch):
    """A hostname is operator-controlled text going into HTML."""
    import opendarts.live.server as server
    monkeypatch.setattr(server, "platform", SimpleNamespace(node=lambda: "a<b>"))
    html = _render_dashboard_html(3)
    assert "<title>a&lt;b&gt; - opendarts dashboard</title>" in html


