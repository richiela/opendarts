def test_the_restart_poll_waits_for_a_different_pid():
    """/api/restart schedules its SIGTERM half a second out, so the
    process it is about to kill answers /api/health perfectly in the
    meantime. Polling for "answered at all" reloads the page into a server
    that is mid-shutdown, which looks exactly like the restart failing."""
    from opendarts.live.server import _read_dashboard_file

    js = _read_dashboard_file("app.js")
    fn = js[js.index("async function waitForRigToComeBack"):js.index("async function restartRig")]
    assert "'/api/health'" in fn
    assert "body.pid !== oldPid" in fn
    # An older build on the machine being updated may have no pid at all.
    assert "body.pid === undefined" in fn
    assert "location.reload()" in js


