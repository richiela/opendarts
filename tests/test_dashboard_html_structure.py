def test_the_maintenance_note_reads_the_flags_from_the_config_document():
    """ONE source for one fact. Both launcher flags are ordinary keys of
    the config document -- the same document the checkbox beside these
    buttons writes -- so the note is drawn from it rather than from a
    second GET /api/restart. Two readers of one flag is exactly how a
    checkbox and the note under it end up disagreeing on screen.

    GET /api/restart still exists and is still tested (FlightDeck reads
    it); what this pins is that the DASHBOARD does not also ask it.
    """
    from opendarts.live.server import _read_dashboard_file

    js = _read_dashboard_file("app.js")
    fn = js[js.index("function renderMaintenanceNote"):]
    fn = fn[:fn.index("async function waitForRigToComeBack")]
    assert "configValue('always_update'" in fn
    assert "configValue('update_on_next_restart'" in fn
    # Every GET of the flags in this file comes from the document. The
    # only /api/restart requests left are the POSTs that actually restart.
    assert "fetch('/api/restart')" not in js
    # ...and the note is redrawn by the one function that applies a
    # document, so a PATCH and the next poll cannot disagree.
    applier = js[js.index("function applyConfigDocument"):]
    applier = applier[:applier.index("async function refreshConfig")]
    assert "renderMaintenanceNote()" in applier


def test_there_is_exactly_one_maintenance_section_holding_all_three_controls():
    """ONE section, three controls. The setting ("Always update on
    restart", a key of the config document) and the two actions that act
    on it (Restart / Update and restart) were built by different hands and
    briefly had a section each; two sections with the same title, one of
    them deciding whether a button in the other is even shown, is how a
    dashboard ends up disagreeing with itself.

    Counted over the WHOLE page, not just the Config tab: a second
    Maintenance heading anywhere is the thing this is watching for.
    """
    html = _render_dashboard_html(3)
    assert html.count('<h2 class="config-section-title">Maintenance</h2>') == 1
    assert html.count('id="always-update-toggle"') == 1

    body = _config_tab(html)
    section = body[body.index("Maintenance</h2>"):]
    assert 'id="always-update-toggle"' in section
    assert 'id="btn-restart"' in section
    assert 'id="btn-update-restart"' in section


def test_the_always_update_checkbox_writes_through_the_config_document():
    """It is a SETTING, so it goes the way every other setting on this tab
    goes -- PATCH /api/config -- and not through the restart route beside
    it. The buttons keep POSTing /api/restart; the checkbox never does."""
    from opendarts.live.server import _read_dashboard_file

    js = _read_dashboard_file("app.js")
    handler = js[js.index("const alwaysUpdateBox = document.getElementById"):]
    handler = handler[:handler.index("});", handler.index("addEventListener")) + 3]
    assert "patchConfig({always_update: on}" in handler
    assert "/api/restart" not in handler
