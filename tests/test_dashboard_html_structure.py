def _config_tab(html: str) -> str:
    """Everything between the Config panel opening and the next panel.

    Sliced panel-to-panel rather than by the div walk used above: a
    `</div>` inside one of this tab's long explanatory comments closes the
    walk early, which is a comment-parsing problem and not a markup one.
    The gap between two panels is the region that actually matters here --
    content in it belongs to no tab, which is the bug that walk was
    written to find in the first place.
    """
    starts = sorted(_panels(html).items(), key=lambda kv: kv[1])
    for index, (name, start) in enumerate(starts):
        if name != "tab-config":
            continue
        end = starts[index + 1][1] if index + 1 < len(starts) else len(html)
        return html[start:end]
    raise AssertionError("#tab-config not found")


def test_maintenance_is_the_last_section_of_the_config_tab():
    """LAST, and that is the design: these are the only two controls on
    the page that take the rig away from whoever is looking at it, so they
    sit below every setting rather than among them, where a mis-aimed
    click lands on a dropdown."""
    body = _config_tab(_render_dashboard_html(3))
    assert '<h2 class="config-section-title">Maintenance</h2>' in body
    titles = re.findall(r'<h2 class="config-section-title">([^<]+)</h2>', body)
    assert titles[-1] == "Maintenance", titles


def test_maintenance_has_both_buttons_and_a_note():
    body = _config_tab(_render_dashboard_html(3))
    assert 'id="btn-restart"' in body
    assert 'id="btn-update-restart"' in body
    assert 'id="restart-note"' in body
    assert ">Restart</button>" in body
    assert ">Update and restart</button>" in body


def test_update_and_restart_starts_hidden_so_a_pinned_rig_never_flashes_it():
    """app.js unhides it only once the config document says always_update
    is false. Shipping it visible would show the button for a moment on every
    rig, including the ones where the plain Restart button already pulls
    -- and a button that appears and then vanishes reads as a bug."""
    body = _config_tab(_render_dashboard_html(3))
    tag = re.search(r'<button id="btn-update-restart"[^>]*>', body)
    assert tag is not None
    assert re.search(r"\bhidden(?=[\s/>])", tag.group(0)), tag.group(0)


def test_maintenance_says_capture_does_not_come_back_on_its_own():
    """Deliberate, and therefore stated where the button is: the page
    reloads into a STOPPED rig. A rig that resumed capture by itself would
    open three cameras in an empty room, and just after a deploy is
    exactly when a human should be in the loop."""
    body = _config_tab(_render_dashboard_html(3))
    section = body[body.index("Maintenance</h2>"):]
    assert "capture does <strong>not</strong> start again on its own" in section
    assert "press Start" in section


